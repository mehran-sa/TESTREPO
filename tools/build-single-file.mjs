/**
 * Builds SA-Invoice-Generator.html: the whole app in one file that opens by
 * double-clicking, with no web server.
 *
 * Browsers refuse to run JavaScript modules from a page opened from disk
 * (file://), so index.html needs a local server. This script produces an
 * equivalent single page instead:
 *   - the modules are bundled into one classic script (esbuild, a build-time
 *     tool only; the output has no dependencies);
 *   - the stylesheets are inlined, with the fonts and icons embedded as data;
 *   - the Excel parser and its worker are embedded as text and started from a
 *     Blob, since a file:// page cannot start a worker from a file path;
 *   - the Content Security Policy allows exactly those inline scripts (by hash)
 *     and still blocks every outbound connection.
 *
 * Run after changing any file under js/, css/ or index.html:
 *
 *     npm install      (once, installs esbuild)
 *     npm run build
 */

import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "SA-Invoice-Generator.html");
const read = (p, enc = "utf8") => readFile(path.join(ROOT, p), enc);

const MIME = { ".otf": "font/otf", ".png": "image/png", ".svg": "image/svg+xml", ".woff2": "font/woff2" };
const dataUri = async file => {
  const mime = MIME[path.extname(file)];
  if (!mime) throw Error("No MIME type for " + file);
  return `data:${mime};base64,${(await readFile(file)).toString("base64")}`;
};

/** Text placed inside a <script> or <style> element must not close it early. */
const guardScript = text => text.replace(/<\/(script)/gi, "<\\/$1").replace(/<!--/g, "<\\!--");
const guardStyle = text => text.replace(/<\/(style)/gi, "<\\/$1");
const sha256 = text => "'sha256-" + createHash("sha256").update(text, "utf8").digest("base64") + "'";

async function inlineCss(href) {
  const file = path.join(ROOT, href);
  let css = await readFile(file, "utf8");
  const urls = [...css.matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)/g)];
  for (const [whole, ref] of urls) {
    if (ref.startsWith("data:")) continue;
    css = css.replace(whole, `url("${await dataUri(path.resolve(path.dirname(file), ref))}")`);
  }
  return `/* ${href} */\n` + css;
}

async function main() {
  let html = await read("index.html");

  // 1. Application bundle.
  const bundle = await build({
    entryPoints: [path.join(ROOT, "js/app.js")],
    bundle: true,
    format: "iife",
    target: ["es2020"],
    write: false,
    legalComments: "inline",
    logLevel: "silent"
  });
  const appJs = guardScript(bundle.outputFiles[0].text);

  // 2. Excel worker: the parser plus the worker code, started from a Blob.
  const workerSource = (await read("js/vendor/xlsx.full.min.js")) + "\n" + (await read("js/import-export/xlsx-worker.js"));
  const workerJs = guardScript(`globalThis.SA_XLSX_WORKER_SOURCE = ${JSON.stringify(workerSource)};`);

  // 3. Stylesheets, in their original order.
  const links = [...html.matchAll(/<link rel="stylesheet" href="([^"]+)">\n?/g)];
  const css = [];
  for (const [, href] of links) css.push(await inlineCss(href));
  html = html.replace(links[0][0], () => `<style>\n${guardStyle(css.join("\n"))}\n</style>\n`);
  for (const [whole] of links.slice(1)) html = html.replace(whole, "");

  // 4. Icons.
  html = html.replace('href="assets/icons/favicon.svg"', `href="${await dataUri(path.join(ROOT, "assets/icons/favicon.svg"))}"`);
  html = html.replace('href="assets/icons/favicon-32.png"', `href="${await dataUri(path.join(ROOT, "assets/icons/favicon-32.png"))}"`);

  // 5. Scripts and the matching policy.
  const scriptTag = '<script type="module" src="js/app.js"></script>';
  if (!html.includes(scriptTag)) throw Error("index.html entry script not found");
  html = html.replace(scriptTag, () => `<script>${workerJs}</script>\n<script>${appJs}</script>`);

  const csp = [
    "default-src 'none'",
    `script-src ${sha256(workerJs)} ${sha256(appJs)}`,
    "style-src 'unsafe-inline'",
    "img-src data: blob:",
    "font-src data:",
    "worker-src blob:",
    "connect-src 'none'",
    "frame-src 'self' about:",
    "object-src 'none'",
    "base-uri 'self' file:",
    "form-action 'none'"
  ].join("; ");
  html = html.replace(/<meta http-equiv="Content-Security-Policy" content="[^"]*">/, () =>
    `<meta http-equiv="Content-Security-Policy" content="${csp}">`);

  html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Built by tools/build-single-file.mjs from index.html, css/ and js/. Do not edit this file; edit the sources and run npm run build. -->");

  await writeFile(OUT, html);
  const kb = Math.round(Buffer.byteLength(html) / 1024);
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${kb} KB)`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
